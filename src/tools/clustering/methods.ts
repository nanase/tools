/** 手法の一覧: 名前・分類・パラメータ・しくみ・凡例。計算の本体は algos.ts */
import type { Params } from './core';
import type { Ctx } from './data';

export const FAMILIES = [
  '代表点ベース',
  '階層',
  '密度ベース',
  '分布ベース',
  'グラフベース',
  'ニューラルネットワーク',
  'グリッドベース',
] as const;
export type Family = (typeof FAMILIES)[number];

/** 凡例の記号: [cl-k の種類, 名前] */
export type Legend = readonly (readonly [string, string])[];

export interface Method {
  id: string;
  name: string;
  g: Family;
  /** パラメータの行の順。seg は選択肢の行（init・cov） */
  keys: readonly string[];
  def: (c: Ctx) => Params;
  /** しくみ: [見出し, 説明] */
  steps: readonly (readonly [string, string])[];
  leg: Legend;
  /** k を手で決めずに自動で決まるか */
  auto?: boolean;
  /** 計算量（距離の計算）。n は点の数、i は反復回数 */
  o: string;
  /** 計算に使う点の数の上限。これより多いと点を抽出して計算する。ないときは描画の上限まで全部の点を使う */
  lim?: number;
  /** Theory.astro の出典のキー */
  refs: readonly string[];
}

