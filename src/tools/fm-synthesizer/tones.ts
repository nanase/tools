/** オペレータの表の 1 行。ベロシティとキースケールは省くと 0.5 と 0.3 */
type O = readonly [r: number, x: number, ar: number, dr: number, sl: number, rr: number, vs?: number, ks?: number];
/** LFO の [速さ, ビブラート, トレモロ, 遅れ] */
type L = readonly [rate: number, vib: number, trem: number, delay: number];
/** 音色の表の 1 行: [アルゴリズム, 帰還量, オペレータ 4 つ, LFO] */
type Row = readonly [alg: number, fb: number, ops: readonly [O, O, O, O], lfo?: L];

/** キャリアに変えたときの出力レベルと、モジュレータに変えたときの変調指数 */
const MOD_L = -8;
const CAR_I = 1;

function toOp([r, x, ar, dr, sl, rr, vs = 0.5, ks = 0.3]: O, carrier: boolean): Op {
  return carrier ? { r, i: CAR_I, l: x, ar, dr, sl, rr, vs, ks } : { r, i: x, l: MOD_L, ar, dr, sl, rr, vs, ks };
}

function build([alg, fb, ops, lfo = [5, 0, 0, 0]]: Row, gain: number, key?: number): Tone {
  const [o0, o1, o2, o3] = ops.map((o, k) => toOp(o, isCarrier(alg, k)));
  const [rate, vib, trem, delay] = lfo;
  const t: Tone = { alg, fb, ops: [o0, o1, o2, o3], lfo: { rate, vib, trem, delay }, gain };
  return key === undefined ? t : { ...t, key };
}

