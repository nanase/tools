/** 音色にベロシティと音の高さの効き、デチューンを重ねる（値が 0 のものは省く） */
function withSens(t: Tone, s: Sens | undefined): Tone {
  if (!s) return t;
  const nz = (v: number | undefined) => (v ? v : undefined);
  return {
    ...t,
    ...(s.fbv ? { fbv: s.fbv } : {}),
    ...(s.fbk ? { fbk: s.fbk } : {}),
    ops: t.ops.map((o, k) => {
      const x: Op = { ...o };
      for (const [f, v] of [
        ['va', nz(s.va[k])],
        ['ka', nz(s.ka?.[k])],
        ['dt', nz(s.dt?.[k])],
      ] as const)
        if (v !== undefined) x[f] = v;
      return x;
    }) as unknown as Tone['ops'],
  };
}

