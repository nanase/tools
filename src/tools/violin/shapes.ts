/** 点の列 [x, y] */
export type Pts = number[][];

/** 点の列を Catmull-Rom で細かくする（透視図でも同じ点を使う） */
export function crPts(pts: Pts, n: number): Pts {
  const out: Pts = [pts[0]];
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[Math.max(0, i - 1)],
      p1 = pts[i],
      p2 = pts[i + 1],
      p3 = pts[Math.min(pts.length - 1, i + 2)];
    for (let k = 1; k <= n; k++) {
      const s = k / n,
        s2 = s * s,
        s3 = s2 * s;
      out.push(
        [0, 1].map(
          (c) =>
            0.5 *
            (2 * p1[c] +
              (p2[c] - p0[c]) * s +
              (2 * p0[c] - 5 * p1[c] + 4 * p2[c] - p3[c]) * s2 +
              (3 * p1[c] - p0[c] - 3 * p2[c] + p3[c]) * s3),
        ),
      );
    }
  }
  return out;
}
/** 半分の輪郭（2 つ目の値が中心からの幅）を、中心線で折り返して閉じた輪郭にする */
const mirrorLoop = (half: Pts): Pts =>
  half.concat(
    half
      .slice(1, -1)
      .reverse()
      .map(([a, c]) => [a, -c]),
  );

