export function chaconne(): Placed[] {
  const out: Placed[] = [];
  let t = 0;
  for (let i = 0; i < DATA.length; i += 11) {
    t += v(DATA.slice(i, i + 3));
    const sf = v(DATA.slice(i + 7, i + 9));
    out.push({
      t: t / 480,
      d: v(DATA.slice(i + 3, i + 6)) / 480,
      n: v(DATA[i + 6]) + 40,
      s: Math.floor(sf / 24),
      f: sf % 24,
      v: v(DATA.slice(i + 9, i + 11)),
    });
  }
  return out;
}
