/** 調号（長調は主音から、短調は平行長調から）の ♯・♭ の数と向き */
const SHARPS: Record<number, number> = {
  0: 0,
  7: 1,
  2: 2,
  9: 3,
  4: 4,
  11: 5,
  6: 6,
  5: -1,
  10: -2,
  3: -3,
  8: -4,
  1: -5,
};
export function keySig(t: number, m: 'maj' | 'min'): string {
  const n = SHARPS[m === 'min' ? (t + 3) % 12 : t] ?? 0;
  return n === 0 ? '' : (n > 0 ? '♯' : '♭').repeat(Math.abs(n));
}
