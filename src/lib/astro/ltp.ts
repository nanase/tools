/**
 * 長期の歳差: 天の北極（平均赤道の極）の向き。Vondrák, Capitaine & Wallace (2011) の式で、±20 万年で使える
 * （frame.ts の IAU 1976 は数百年まで）。係数は SOFA の iauLtpequ による。
 * 向きは J2000 の平均赤道と分点の直交座標（x が春分点、z が J2000 の天の北極）。
 * y の向きは SOFA の試験値（−2500 年）と、トゥバン（紀元前 2800 年頃）・ベガ（西暦 1 万 4 千年頃）に近づくことで確かめた
 */
import type { Vec3 } from './vec';

const AS = Math.PI / 180 / 3600;
/** X・Y の多項式（t は J2000 からのユリウス世紀） */
const POL = [
  [5453.282155, 0.4252841, -0.00037173, -0.000000152],
  [-73750.93035, -0.7675452, -0.00018725, 0.000000231],
] as const;
/** 周期項 [周期（世紀）, X の cos, Y の cos, X の sin, Y の sin]（″） */
const PER = [
  [256.75, -819.940624, 75004.344875, 81491.287984, 1558.515853],
  [708.15, -8444.676815, 624.033993, 787.163481, 7774.939698],
  [274.2, 2600.009459, 1251.136893, 1251.296102, -2219.534038],
  [241.45, 2755.17563, -1102.212834, -1257.950837, -2523.969396],
  [2309, -167.659835, -2660.66498, -2966.79973, 247.850422],
  [492.2, 871.855056, 699.291817, 639.744522, -846.485643],
  [396.1, 44.769698, 153.16722, 131.600209, -1393.124055],
  [288.9, -512.313065, -950.865637, -445.040117, 368.526116],
  [231.1, -819.415595, 499.754645, 584.522874, 749.045012],
  [1610, -538.071099, -145.18821, -89.756563, 444.704518],
  [620, -189.793622, 558.116553, 524.42963, 235.934465],
  [157.87, -402.922932, -23.923029, -13.549067, 374.049623],
  [220.3, 179.516345, -165.405086, -210.157124, -171.33018],
  [1200, -9.814756, 9.344131, -44.919798, -22.899655],
] as const;

/** ユリウス年（2000 なら J2000.0）の天の北極 */
export function ltpPole(epj: number): Vec3 {
  const t = (epj - 2000) / 100;
  let x = 0,
    y = 0;
  for (const [p, xc, yc, xs, ys] of PER) {
    const a = (2 * Math.PI * t) / p,
      c = Math.cos(a),
      s = Math.sin(a);
    x += c * xc + s * xs;
    y += c * yc + s * ys;
  }
  let w = 1;
  for (let j = 0; j < 4; j++) {
    x += (POL[0][j] as number) * w;
    y += (POL[1][j] as number) * w;
    w *= t;
  }
  x *= AS;
  y *= AS;
  return [x, y, Math.sqrt(Math.max(0, 1 - x * x - y * y))];
}
